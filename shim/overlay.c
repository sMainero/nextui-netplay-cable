static void put_px(const OVL_Target* t, int x, int y) {
	if (x < 0 || y < 0 || (unsigned)x >= t->width || (unsigned)y >= t->height) return;
	uint8_t* row = (uint8_t*)t->pixels + (size_t)y * t->pitch;

	switch (t->format) {
	case OVL_FMT_XRGB8888: ((uint32_t*)row)[x] = 0x00FFFFFFu; break;
	case OVL_FMT_0RGB1555: ((uint16_t*)row)[x] = 0x7FFF; break;
	default:               ((uint16_t*)row)[x] = 0xFFFF; break;
	}
}

void OVL_dim(const OVL_Target* t) {
	for (unsigned y = 0; y < t->height; y++) {
		uint8_t* row = (uint8_t*)t->pixels + (size_t)y * t->pitch;
		if (t->format == OVL_FMT_XRGB8888) {
			uint32_t* p = (uint32_t*)row;
			for (unsigned x = 0; x < t->width; x++) p[x] = (p[x] >> 1) & 0x7F7F7F7Fu;
		} else {
			uint16_t* p = (uint16_t*)row;
			uint16_t mask = (t->format == OVL_FMT_RGB565) ? 0x7BEF : 0x3DEF;
			for (unsigned x = 0; x < t->width; x++) p[x] = (p[x] >> 1) & mask;
		}
	}
}

static int OVL_textWidth_n(const char* text, int n, int scale) {
	if (n <= 0) return 0;
	return (n * OVL_ADVANCE - 1) * scale;
}

int OVL_textWidth(const char* text, int scale) {
	int n = (int)strlen(text);
	if (!n) return 0;
	/* No trailing spacing column on the last glyph. */
	return (n * OVL_ADVANCE - 1) * scale;
}

void OVL_drawText(const OVL_Target* t, int x, int y, const char* text, int scale) {
	for (const char* c = text; *c; c++) {
		unsigned char ch = (unsigned char)*c;
		if (ch >= FIRST_CH && ch <= LAST_CH) {
			const uint8_t* g = GLYPHS[ch - FIRST_CH];
			for (int gy = 0; gy < OVL_GLYPH_H; gy++) {
				uint8_t bits = g[gy];
				for (int gx = 0; gx < OVL_GLYPH_W; gx++) {
					if (!(bits & (1 << (OVL_GLYPH_W - 1 - gx)))) continue;
					for (int sy = 0; sy < scale; sy++)
						for (int sx = 0; sx < scale; sx++)
							put_px(t, x + (gx * scale) + sx, y + (gy * scale) + sy);
				}
			}
		}
		x += OVL_ADVANCE * scale;
	}
}

void OVL_fillRect(const OVL_Target* t, int x, int y, int w, int h) {
	for (int yy = y; yy < y + h; yy++)
		for (int xx = x; xx < x + w; xx++)
			put_px(t, xx, yy);
}

int OVL_wrap(const char* text, int scale, int max_w,
             char lines[][OVL_MAX_LINE], int max_lines) {
	int n = 0;
	const char* p = text;

	while (*p && n < max_lines) {
		/* Longest run of whole words that still fits. */
		int best = 0;
		for (const char* q = p;; q++) {
			if (*q && *q != ' ') continue;

			int len = (int)(q - p);
			if (len > OVL_MAX_LINE - 1) break;

			char probe[OVL_MAX_LINE];
			memcpy(probe, p, len);
			probe[len] = '\0';
			if (OVL_textWidth(probe, scale) <= max_w) best = len;
			else break;

			if (!*q) break;
		}

		/* A single word longer than the line: emit what fits rather than loop. */
		if (best == 0) {
			best = (int)strlen(p);
			if (best > OVL_MAX_LINE - 1) best = OVL_MAX_LINE - 1;
			while (best > 1 && OVL_textWidth_n(p, best, scale) > max_w) best--;
		}

		memcpy(lines[n], p, best);
		lines[n][best] = '\0';
		n++;

		p += best;
		while (*p == ' ') p++;
	}
	return n;
}

int OVL_textInk(const char* text, int scale, int* bearing) {
	int first = -1, last = -1;
	int i = 0;

	for (const char* c = text; *c; c++, i++) {
		unsigned char ch = (unsigned char)*c;
		if (ch < FIRST_CH || ch > LAST_CH) continue;

		const uint8_t* g = GLYPHS[ch - FIRST_CH];
		uint8_t any = 0;
		for (int gy = 0; gy < OVL_GLYPH_H; gy++) any |= g[gy];
		if (!any) continue; /* blank glyph, eg. space */

		for (int gx = 0; gx < OVL_GLYPH_W; gx++) {
			if (!(any & (1 << (OVL_GLYPH_W - 1 - gx)))) continue;
			int col = i * OVL_ADVANCE + gx;
			if (first < 0 || col < first) first = col;
			if (col > last) last = col;
		}
	}

	if (first < 0) { /* nothing to draw */
		if (bearing) *bearing = 0;
		return 0;
	}
	if (bearing) *bearing = first * scale;
	return (last - first + 1) * scale;
}
